BENCH_VLAN_BASE = 1100  # bench underlay VLAN ids, distinct from the demo's 100..


def bench_overlay(i):
    # Reuse the demo overlay subnets: already enumerated by the driver and their
    # provider already matches the NAD pattern <subnet>.default.ovn.
    o = overlay(i)
    return {"subnet": o["subnet"], "provider": o["provider"], "new": False}


def bench_underlay(i):
    # The demo underlay providers (external.vlanX-subnet.ovn) do NOT fit the NAD
    # <name>.<ns>.ovn pattern, so the benchmark provisions its own underlay
    # subnets whose provider == <subnet>.default.ovn (NAD name == subnet name).
    name = f"bench-u{i}"
    return {
        "subnet": name,
        "provider": f"{name}.default.ovn",
        "vlan": f"bench-vlan{i}",
        "id": BENCH_VLAN_BASE + i,
        "cidr": f"10.{210 + i}.0.0/24",
        "gw": f"10.{210 + i}.0.1",
        "new": True,
    }


def bench_entries(mode, count):
    if mode == "overlay":
        if count > MAX_PAIRS:
            raise SystemExit(f"overlay count {count} exceeds {MAX_PAIRS} subnets")
        items = [bench_overlay(i) for i in range(1, count + 1)]
    elif mode == "underlay":
        if count > MAX_PAIRS:
            raise SystemExit(f"underlay count {count} exceeds {MAX_PAIRS} subnets")
        items = [bench_underlay(i) for i in range(1, count + 1)]
    elif mode == "mixed":
        pairs = count // 2
        u_count = pairs + (count - 2 * pairs)  # odd -> one more underlay
        o_count = pairs
        if u_count > MAX_PAIRS or o_count > MAX_PAIRS:
            raise SystemExit(f"mixed count {count} exceeds {MAX_PAIRS}/{MAX_PAIRS}")
        items = [bench_underlay(i) for i in range(1, u_count + 1)]
        items += [bench_overlay(i) for i in range(1, o_count + 1)]
    else:
        raise SystemExit(f"unknown mode {mode!r}")
    for n, it in enumerate(items, start=1):
        it["ifname"] = f"net{n}"
    return items


def _write(path, lines):
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path)


def write_bench(mode, count, outdir):
    os.makedirs(outdir, exist_ok=True)
    entries = bench_entries(mode, count)

    # Benchmark subnets — only the underlay ones need creating (overlay reuses
    # the demo subnets). Deploy these BEFORE/with a plugin restart so the driver
    # enumerates them. Needs ProviderNetwork external (eth1 via clab).
    new = [e for e in entries if e["new"]]
    subnets_path = os.path.join(outdir, "subnets.yaml")
    if new:
        out = [
            "# Benchmark underlay subnets (Multus-compatible <name>.default.ovn providers).",
            "# GENERATED by generate.py bench. Needs ProviderNetwork external (eth1 via clab).",
            "---", "apiVersion: kubeovn.io/v1", "kind: ProviderNetwork",
            "metadata:", "  name: external", "spec:", "  defaultInterface: eth1",
        ]
        for e in new:
            out += [
                "---", "apiVersion: kubeovn.io/v1", "kind: Vlan", "metadata:",
                f"  name: {e['vlan']}", "  labels:", "    bench: nic-dra",
                "spec:", f"  id: {e['id']}", "  provider: external",
                "---", "apiVersion: kubeovn.io/v1", "kind: Subnet", "metadata:",
                f"  name: {e['subnet']}", "  labels:", "    bench: nic-dra",
                "spec:", "  protocol: IPv4",
                f"  cidrBlock: {e['cidr']}", f"  gateway: {e['gw']}",
                f"  vlan: {e['vlan']}", f"  provider: {e['provider']}",
            ]
        _write(subnets_path, out)
    elif os.path.exists(subnets_path):
        os.remove(subnets_path)

    # DRA fixture: one ResourceClaim with N requests + a netshoot pod.
    reqs, cfgs = [], []
    for n, e in enumerate(entries):
        reqs += [
            f"      - name: nic{n}", "        exactly:",
            "          deviceClassName: nic.kubeovn.io", "          selectors:",
            "            - cel:",
            f"                expression: \"device.attributes['nic.kubeovn.io'].subnetName == '{e['subnet']}'\"",
            "          count: 1",
        ]
        cfgs += [
            f"      - requests: [\"nic{n}\"]", "        opaque:",
            "          driver: nic.kubeovn.io", "          parameters:",
            f"            apiVersion: {CONFIG_API}", "            kind: NicConfig",
            f"            interfaceName: {e['ifname']}",
        ]
    dra = [
        f"# DRA benchmark: {count} NICs ({mode}). GENERATED by generate.py bench.",
        "---", "apiVersion: resource.k8s.io/v1", "kind: ResourceClaim",
        "metadata:", "  name: bench-dra", "  namespace: default", "spec:",
        "  devices:", "    requests:", *reqs, "    config:", *cfgs,
        "---", "apiVersion: v1", "kind: Pod", "metadata:", "  name: bench-dra",
        "  namespace: default", "spec:", "  resourceClaims:", "    - name: nics",
        "      resourceClaimName: bench-dra", "  containers:", "    - name: demo",
        f"      image: {NETSHOOT}", "      command: [\"sleep\", \"infinity\"]",
        "      resources:", "        claims:", "          - name: nics",
        "      securityContext:", "        capabilities:", "          add: [\"NET_ADMIN\"]",
    ]
    _write(os.path.join(outdir, "dra.yaml"), dra)

    # Multus fixture: N NetworkAttachmentDefinitions + a netshoot pod annotated
    # with all of them. kube-ovn reads the provider from the NAD's CNI config.
    nets = ", ".join(f"default/{e['subnet']}@{e['ifname']}" for e in entries)
    mu = [f"# Multus benchmark: {count} NICs ({mode}). GENERATED by generate.py bench."]
    for e in entries:
        cfg = ('{"cniVersion":"0.3.0","type":"kube-ovn",'
               '"server_socket":"/run/openvswitch/kube-ovn-daemon.sock",'
               f'"provider":"{e["provider"]}"}}')
        mu += [
            "---", "apiVersion: k8s.cni.cncf.io/v1",
            "kind: NetworkAttachmentDefinition", "metadata:",
            f"  name: {e['subnet']}", "  namespace: default", "spec:",
            f"  config: '{cfg}'",
        ]
    mu += [
        "---", "apiVersion: v1", "kind: Pod", "metadata:", "  name: bench-multus",
        "  namespace: default", "  annotations:",
        f"    k8s.v1.cni.cncf.io/networks: {nets}", "spec:", "  containers:",
        "    - name: demo", f"      image: {NETSHOOT}",
        "      command: [\"sleep\", \"infinity\"]", "      securityContext:",
        "        capabilities:", "          add: [\"NET_ADMIN\"]",
    ]
    _write(os.path.join(outdir, "multus.yaml"), mu)

    # Multus hot-plug fixture: pod starts with only the first HOTPLUG_BASE
    # attachments; the remaining N-HOTPLUG_BASE are added afterward by patching
    # the k8s.v1.cni.cncf.io/networks annotation, which
    # multus-dynamic-networks-controller reconciles onto the running pod with no
    # restart. Compares against static Multus (all N upfront, serial in the
    # sandbox path) and DRA (parallel IPAM). Skipped if count <= HOTPLUG_BASE
    # (nothing left to hot-plug).
    base = min(HOTPLUG_BASE, count)
    if base < count:
        initial = entries[:base]
        hp = [f"# Multus hot-plug benchmark: {base}->{count} NICs ({mode}). GENERATED by generate.py bench."]
        for e in entries:
            cfg = ('{"cniVersion":"0.3.0","type":"kube-ovn",'
                   '"server_socket":"/run/openvswitch/kube-ovn-daemon.sock",'
                   f'"provider":"{e["provider"]}"}}')
            hp += [
                "---", "apiVersion: k8s.cni.cncf.io/v1",
                "kind: NetworkAttachmentDefinition", "metadata:",
                f"  name: {e['subnet']}", "  namespace: default", "spec:",
                f"  config: '{cfg}'",
            ]
        initial_nets = ", ".join(f"default/{e['subnet']}@{e['ifname']}" for e in initial)
        hp += [
            "---", "apiVersion: v1", "kind: Pod", "metadata:",
            "  name: bench-multus-hotplug", "  namespace: default", "  annotations:",
            f"    k8s.v1.cni.cncf.io/networks: {initial_nets}", "spec:", "  containers:",
            "    - name: demo", f"      image: {NETSHOOT}",
            "      command: [\"sleep\", \"infinity\"]", "      securityContext:",
            "        capabilities:", "          add: [\"NET_ADMIN\"]",
        ]
        _write(os.path.join(outdir, "multus-hotplug.yaml"), hp)
        with open(os.path.join(outdir, "multus-hotplug-full-networks.txt"), "w") as f:
            f.write(nets)
        print("wrote", os.path.join(outdir, "multus-hotplug-full-networks.txt"))
    else:
        for name in ("multus-hotplug.yaml", "multus-hotplug-full-networks.txt"):
            p = os.path.join(outdir, name)
            if os.path.exists(p):
                os.remove(p)


