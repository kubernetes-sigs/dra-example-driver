#!/usr/bin/env python3
"""Generate the kube-ovn DRA NIC demo fixtures and scaling examples.

Produces, under demo/nic-example/:
  - 00-kube-ovn-subnets.yaml        (ProviderNetwork + 8 VLAN + 8 overlay subnets)
  - examples/<N>nic.yaml            (ResourceClaim + netshoot Pod with N NICs)

and prints the containerlab / FRR / bridge snippets needed for the VLAN underlay
to actually pass traffic (these are host-side and applied by `make clab-deploy`).

The demo attaches an equal split of underlay (VLAN) and overlay (OVN) NICs to a
netshoot pod, so the spin-up time can be measured against the Multus baseline
(~5s/NIC, serial) at increasing NIC counts.

Subnet scheme:
  underlay  vlan<100*i>-subnet  VLAN <100*i>  172.<22+i>.0.0/24  gw .253
  overlay   ovn-subnet[-i]      10.<199+i>.0.0/24                gw .1

Usage:
  python3 demo/nic-example/examples/generate.py        # default counts 2,4,8,16
  MAX_VLANS=8 COUNTS="2,6,12" python3 .../generate.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NIC_DIR = os.path.dirname(HERE)

MAX_PAIRS = int(os.environ.get("MAX_VLANS", "8"))  # 8 underlay + 8 overlay available
# Peer counts for the shared-subnet fixtures (07/08) — independent of
# MAX_PAIRS (that governs distinct subnet-pair availability for the scaling
# examples; these fixtures use exactly ONE shared subnet regardless of count).
OVERLAY_PEER_COUNT = int(os.environ.get("OVERLAY_PEER_COUNT", "4"))
VLAN_PEER_COUNT = int(os.environ.get("VLAN_PEER_COUNT", "4"))
COUNTS = [int(c) for c in os.environ.get("COUNTS", "2,4,8,16").split(",")]
# NICs the Multus hot-plug benchmark pod starts with before hot-plugging the rest,
# via the public k8snetworkplumbingwg/multus-dynamic-networks-controller.
HOTPLUG_BASE = int(os.environ.get("HOTPLUG_BASE", "2"))

CONFIG_API = "nic.resource.kube-ovn.io/v1alpha1"
NETSHOOT = "nicolaka/netshoot@sha256:47b907d662d139d1e2f22bfe14f4efca1e3f1feed283572f47c970c780c03b61"


def underlay(i):  # i = 1..MAX_PAIRS
    vid = 100 * i
    return {
        "vlan": f"vlan{vid}",
        "subnet": f"vlan{vid}-subnet",
        "id": vid,
        "cidr": f"172.{22 + i}.0.0/24",
        "gw": f"172.{22 + i}.0.253",
        "provider": f"external.vlan{vid}-subnet.ovn",
    }


def overlay(i):  # i = 1..MAX_PAIRS
    name = "ovn-subnet" if i == 1 else f"ovn-subnet-{i}"
    return {
        "subnet": name,
        "cidr": f"10.{199 + i}.0.0/24",
        "gw": f"10.{199 + i}.0.1",
        "provider": f"{name}.default.ovn",
    }


def write_subnets():
    out = [
        "# kube-ovn ProviderNetwork, VLANs and subnets for the DRA NIC driver demo.",
        "#",
        f"# {MAX_PAIRS} VLAN underlay subnets (vlan100-subnet .. vlan{100*MAX_PAIRS}-subnet) and",
        f"# {MAX_PAIRS} OVN overlay subnets (ovn-subnet, ovn-subnet-2 .. ovn-subnet-{MAX_PAIRS}).",
        "# The scaling examples under examples/ attach an equal split of these to a pod.",
        "#",
        "# GENERATED by examples/generate.py — edit there, not here.",
        "# VLAN underlay requires the matching containerlab wiring (make clab-deploy).",
        "---",
        "apiVersion: kubeovn.io/v1",
        "kind: ProviderNetwork",
        "metadata:",
        "  name: external",
        "spec:",
        "  defaultInterface: eth1",
    ]
    for i in range(1, MAX_PAIRS + 1):
        u = underlay(i)
        out += [
            "---",
            "apiVersion: kubeovn.io/v1",
            "kind: Vlan",
            "metadata:",
            f"  name: {u['vlan']}",
            "spec:",
            f"  id: {u['id']}",
            "  provider: external",
            "---",
            "apiVersion: kubeovn.io/v1",
            "kind: Subnet",
            "metadata:",
            f"  name: {u['subnet']}",
            "spec:",
            "  protocol: IPv4",
            f"  cidrBlock: {u['cidr']}",
            f"  # FRR gateway on eth1.{u['id']} (.253) is the L3 next-hop; .1 has no device.",
            f"  gateway: {u['gw']}",
            "  excludeIps:",
            f"    - {u['gw']}",
            f"    - 172.{22 + i}.0.254",
            f"  vlan: {u['vlan']}",
            f"  provider: {u['provider']}",
        ]
    for i in range(1, MAX_PAIRS + 1):
        o = overlay(i)
        out += [
            "---",
            "# OVN overlay subnet (no VLAN/eth1 dependency). Secondary OVN NICs need a",
            "# dedicated provider '<name>.<namespace>.ovn' (the default 'ovn' names eth0).",
            "apiVersion: kubeovn.io/v1",
            "kind: Subnet",
            "metadata:",
            f"  name: {o['subnet']}",
            "spec:",
            "  protocol: IPv4",
            f"  cidrBlock: {o['cidr']}",
            f"  gateway: {o['gw']}",
            f"  provider: {o['provider']}",
        ]
    path = os.path.join(NIC_DIR, "00-kube-ovn-subnets.yaml")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path)


def nic_entries(count):
    """Return list of (ifname, subnet, kind) with underlay first, equal split."""
    pairs = count // 2
    extra_underlay = count - 2 * pairs  # odd counts get one more underlay
    u_count = pairs + extra_underlay
    o_count = pairs
    if u_count > MAX_PAIRS or o_count > MAX_PAIRS:
        raise SystemExit(f"count {count} exceeds available {MAX_PAIRS} underlay/{MAX_PAIRS} overlay")
    entries = []
    idx = 1
    for i in range(1, u_count + 1):
        entries.append((f"net{idx}", underlay(i)["subnet"], "underlay"))
        idx += 1
    for i in range(1, o_count + 1):
        entries.append((f"net{idx}", overlay(i)["subnet"], "overlay"))
        idx += 1
    return entries


